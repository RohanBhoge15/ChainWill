/**
 * Creates backend/.env with freshly generated secrets (JWT secret, AES master
 * key, VAPID keys, admin password). Existing values are never overwritten, so
 * it is safe to run again; missing keys are appended.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import webpush from "web-push";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envFile = path.join(root, ".env");

const existing = {};
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (match) existing[match[1]] = match[2];
  }
}

const vapid = webpush.generateVAPIDKeys();
const defaults = {
  PORT: "4000",
  JWT_SECRET: crypto.randomBytes(48).toString("hex"),
  SERVER_ENCRYPTION_KEY: crypto.randomBytes(32).toString("hex"),
  VAPID_PUBLIC_KEY: vapid.publicKey,
  VAPID_PRIVATE_KEY: vapid.privateKey,
  WEB_PUSH_CONTACT: "mailto:admin@chainwill.local",
  GANACHE_RPC_URL: "http://127.0.0.1:7545",
  GANACHE_MNEMONIC: '"myth like bonus scare over problem client lizard pioneer submit female collect"',
  DB_FILE: "data/chainwill.db",
  STORAGE_DRIVER: "local",
  ADMIN_EMAIL: "admin@chainwill.local",
  ADMIN_PASSWORD: crypto.randomBytes(9).toString("base64url"),
  ENABLE_DEMO_TOOLS: "true",
};

// The VAPID pair must stay a pair: only generate one if neither half exists.
if (existing.VAPID_PUBLIC_KEY || existing.VAPID_PRIVATE_KEY) {
  delete defaults.VAPID_PUBLIC_KEY;
  delete defaults.VAPID_PRIVATE_KEY;
}

const missing = Object.entries(defaults).filter(([key]) => !(key in existing));
if (missing.length === 0) {
  console.log("[setup] backend/.env is complete — nothing to do");
} else {
  const header = fs.existsSync(envFile) ? "" : "# ChainWill backend configuration — generated by `npm run setup`. Do not commit.\n";
  const body = missing.map(([key, value]) => `${key}=${value}`).join("\n");
  fs.appendFileSync(envFile, `${header}${body}\n`);
  console.log(`[setup] wrote ${missing.length} value(s) to backend/.env: ${missing.map(([k]) => k).join(", ")}`);
  if (missing.some(([key]) => key === "ADMIN_PASSWORD")) {
    console.log(`[setup] admin login → ${existing.ADMIN_EMAIL || defaults.ADMIN_EMAIL} / ${defaults.ADMIN_PASSWORD}`);
  }
}
